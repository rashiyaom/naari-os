#!/usr/bin/env python3
"""Generate full-resolution, 4-bit RGB565 backgrounds (no device decoder).
Run with Python + Pillow. All artwork is procedural and reproducible.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFilter
import math, random
W,H=410,502
ROOT=Path(__file__).resolve().parents[1]

def frame(kind):
    img=Image.new('RGB',(W,H));p=img.load()
    for y in range(H):
        for x in range(W):
            if kind==1:
                r,g,b=3,13,12
            elif kind==2:
                v=math.exp(-((y-(280+65*math.sin(x/94))) / 72)**2)
                q=math.exp(-((y-(220+40*math.cos(x/112))) / 47)**2)
                r,g,b=7+18*q,4+42*v,18+38*q+18*v
            elif kind==3:
                v=math.exp(-((y-320)/105)**2)
                r,g,b=12+84*v,5+34*v,12+25*v
            else:
                v=math.exp(-((x-205)**2+(y-272)**2)/28000)
                r,g,b=3,10+14*v,15+18*v
            # Keep the clock and system overlays legible.
            fade=0.40 if y<190 else 0.80 if y>420 else 1
            p[x,y]=(int(r*fade),int(g*fade),int(b*fade))
    d=ImageDraw.Draw(img)
    if kind==1:
        for offset in range(-190,550,22):
            points=[]
            for y in range(30,H,2):
                x=offset+48*math.sin(y/85)+23*math.sin(y/41)
                points.append((int(x),y))
            d.line(points,fill=(19,54,43),width=1)
    if kind==2:
        rng=random.Random(7)
        for _ in range(100):
            x,y=rng.randrange(W),rng.randrange(H)
            d.point((x,y),fill=(42,48,70))
    if kind==3:
        for y in range(336,H,2):
            ridge=[(x,y+12*math.sin(x/68)) for x in range(0,W,3)]
            d.line(ridge,fill=(20+int((H-y)/6),10,20),width=3)
    if kind==4:
        for x in range(-200,650,32):d.line([(205+(x-205)*.22,190),(x,500)],fill=(12,33,40),width=1)
        for y in [211,240,273,313,359,415,481]:d.line([(0,y),(410,y)],fill=(12,33,40),width=1)
    return img

out=['// Generated by tools/generate_wallpapers.py. Full 410 x 502 RGB565 palettes.\n#pragma once\n#include <cstdint>\nnamespace SheShield::WallpaperAssets {\n']
for i in range(1,5):
    img=frame(i).quantize(colors=16,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.FLOYDSTEINBERG)
    palette=img.getpalette()[:48];rgb=[((r&248)<<8)|((g&252)<<3)|(b>>3) for r,g,b in zip(palette[::3],palette[1::3],palette[2::3])]
    data=list(img.getdata());packed=[(data[n]<<4)|data[n+1] for n in range(0,len(data),2)]
    out.append(f'inline constexpr uint16_t palette{i}[16] = {{'+','.join(hex(c) for c in rgb)+'};\n')
    out.append(f'inline constexpr uint8_t pixels{i}[{len(packed)}] = {{\n')
    out.extend(','.join(str(b) for b in packed[n:n+64])+',\n' for n in range(0,len(packed),64));out.append('};\n')
out.append('inline constexpr const uint16_t* palettes[] = {nullptr,palette1,palette2,palette3,palette4};\ninline constexpr const uint8_t* pixels[] = {nullptr,pixels1,pixels2,pixels3,pixels4};\n}\n')
(ROOT/'main/ui/wallpaper_assets.h').write_text(''.join(out))
print('Generated four complete wallpapers: 411,640 bytes + palettes')
