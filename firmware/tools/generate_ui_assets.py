SIZES = [18, 22, 26, 32, 44, 50, 60]

def pack(im):
    values = [(v * 15 + 127) // 255 for v in im.getdata()]
    if len(values) % 2: values.append(0)
    return bytes((values[i] << 4) | values[i+1] for i in range(0, len(values), 2))

def array(name, data):
    return 'inline constexpr uint8_t '+name+'[] = {\n'+''.join('    '+','.join(f'0x{b:02x}' for b in data[i:i+24])+',\n' for i in range(0,len(data),24))+'};\n'

lines = ['// Generated by firmware/tools/generate_ui_assets.py; do not hand edit.\n',
         '// Inter by Rasmus Andersson, SIL OFL: tools/assets/Inter-LICENSE.txt\n',
         '#pragma once\n#include <cstdint>\nnamespace SheShield::UiAssets {\n',
         'enum class Font : uint8_t { '+', '.join(x[0] for x in STYLES)+' };\n',
         'enum class Symbol : uint8_t { '+', '.join(SYMBOLS)+' };\n',
         'struct Glyph { uint32_t offset; uint8_t width, height, advance; int8_t x, y; };\n',
         'struct FontData { const uint8_t* pixels; const Glyph* glyphs; uint8_t size; };\n',
         'inline constexpr uint32_t codepoints[] = {'+','.join(str(ord(c)) for c in CHARS)+'};\n']
fontrefs = []
for name, size, weight in STYLES:
    font = ImageFont.truetype(str(ASSETS/'InterVariable.ttf'), size)
    axes = font.get_variation_axes()
    font.set_variation_by_axes([weight if a['name'] == b'Weight' else a['default'] for a in axes])
    pixels, glyphs = bytearray(), []
    for ch in CHARS:
        # Clock/timer need only digits + punctuation. Still retain table indices.
        if name in ['Clock', 'Timer'] and ch not in '0123456789:%.- ':
            glyphs.append((len(pixels), 0, 0, 0, 0, 0)); continue
        x0,y0,x1,y1 = font.getbbox(ch, anchor='ls')
        w,h = x1-x0, y1-y0
        im = Image.new('L', (max(1,w),max(1,h)))
        ImageDraw.Draw(im).text((-x0,-y0), ch, font=font, fill=255, anchor='ls')
        glyphs.append((len(pixels), w,h, round(font.getlength(ch)), x0,size+y0))
        pixels.extend(pack(im))
    lines += [array('font'+name, pixels), 'inline constexpr Glyph glyph'+name+'[] = {\n'+''.join('    {'+','.join(map(str,g))+'},\n' for g in glyphs)+'};\n']
    fontrefs.append('{font'+name+',glyph'+name+','+str(size)+'}')
lines += ['inline constexpr FontData fonts[] = {'+','.join(fontrefs)+'};\n']
iconrefs=[]
for name, paths in SYMBOLS.items():
    refs=[]
    for size in SIZES:
        svg=f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><g fill="none" stroke="white" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">{paths}</g></svg>'
        im=Image.open(io.BytesIO(cairosvg.svg2png(bytestring=svg.encode(),output_width=size*3,output_height=size*3))).getchannel('A').resize((size,size),Image.Resampling.LANCZOS)
        key='icon'+name+str(size)
        lines.append(array(key,pack(im))); refs.append(key)
    iconrefs.append('{'+','.join(refs)+'}')
lines += ['inline constexpr uint8_t symbolSizes[] = {'+','.join(map(str,SIZES))+'};\n',
          'inline constexpr const uint8_t* symbols[][7] = {'+','.join(iconrefs)+'};\n',
          '} // namespace SheShield::UiAssets\n']
