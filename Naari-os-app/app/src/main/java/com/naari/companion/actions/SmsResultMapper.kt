package com.naari.companion.actions

import android.app.Activity
import android.telephony.SmsManager

/**
 * Maps Android telephony result codes into human-readable, actionable failure reasons.
 * Ref: PRD Section 7 & Master Prompt Task 9.
 */
object SmsResultMapper {

    const val RESULT_OK = -1
    const val ERROR_GENERIC_FAILURE_CODE = SmsManager.RESULT_ERROR_GENERIC_FAILURE
    const val ERROR_RADIO_OFF_CODE = SmsManager.RESULT_ERROR_RADIO_OFF
    const val ERROR_NULL_PDU_CODE = SmsManager.RESULT_ERROR_NULL_PDU
    const val ERROR_NO_SERVICE_CODE = SmsManager.RESULT_ERROR_NO_SERVICE
    const val ERROR_LIMIT_EXCEEDED_CODE = 5 // SmsManager.RESULT_ERROR_LIMIT_EXCEEDED

    /**
     * Returns null if [resultCode] is [Activity.RESULT_OK] or [RESULT_OK], or a human-readable failure reason string.
     */
    fun mapSentResultCode(resultCode: Int): String? {
        if (resultCode == RESULT_OK) return null

        return when (resultCode) {
            SmsManager.RESULT_ERROR_GENERIC_FAILURE ->
                "Generic carrier error: SMS rejected by cellular network"
            SmsManager.RESULT_ERROR_RADIO_OFF ->
                "Cellular radio is off or device is in Airplane mode"
            SmsManager.RESULT_ERROR_NULL_PDU ->
                "Null PDU error generated by telephony subsystem"
            SmsManager.RESULT_ERROR_NO_SERVICE ->
                "No cellular service or emergency-only network coverage"
            ERROR_LIMIT_EXCEEDED_CODE ->
                "Android OS SMS rate limit exceeded"
            else ->
                "SMS transmission failed with carrier code $resultCode"
        }
    }
}
